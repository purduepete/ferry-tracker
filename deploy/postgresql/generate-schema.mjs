// Generates a review artifact only. It never opens a database.
import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';

async function sourceModule(path) {
    const source = await readFile(new URL(path, import.meta.url), 'utf8');
    const { outputText } = ts.transpileModule(source, {
        compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
    });
    return import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
}
const { migrations } = await sourceModule('../../server/src/db/schema.ts');
const { views } = await sourceModule('../../server/src/db/views.ts');
const statements = migrations
    .flatMap((migration) => migration.statements)
    .map((sql) =>
        sql
            .replace(/\bid INTEGER PRIMARY KEY/g, 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
            .replace(/\bbyte_size INTEGER\b/g, 'byte_size BIGINT')
            .replace(/\bCREATE TABLE (\w+)/g, 'CREATE TABLE public.$1')
            .replace(/\bALTER TABLE (\w+)/g, 'ALTER TABLE public.$1')
            .replace(/\bON (\w+) \(/g, 'ON public.$1 (')
    );
const viewStatements = views.map((view) => {
    const sql = view.sql.replace('CREATE VIEW ', 'CREATE VIEW public.');
    return view.name === 'v_sailing_fill' ? sql.replace(/\b100\.0 \*/g, '100.0::double precision *') : sql;
});
const sql = [
    '-- Reviewed deployment step only. Runtime startup never executes this file.',
    '-- Keep ISO-8601 timestamps as TEXT and 0/1 flags as INTEGER to preserve source semantics.',
    'BEGIN;',
    'CREATE TABLE public.solutiondeploy_schema (app_id TEXT PRIMARY KEY, version INTEGER NOT NULL);',
    'CREATE TABLE public.solutiondeploy_import (app_id TEXT PRIMARY KEY, source_sha256 TEXT NOT NULL, validation JSONB NOT NULL, imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);',
    'CREATE TABLE public.schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL);',
    ...statements.map((statement) => `${statement};`),
    ...viewStatements.map((statement) => `${statement};`),
    "INSERT INTO public.solutiondeploy_schema (app_id, version) VALUES ('ferry-tracker', 1);",
    'COMMIT;',
    '',
].join('\n\n');
await writeFile(new URL('001_initial.sql', import.meta.url), sql);
